/** A Supabase database host: the poolers (*.pooler.supabase.com) or a project's own host. */
export function isSupabaseHost(url: string): boolean {
  try {
    return /(^|\.)supabase\.(com|co)$/.test(new URL(url).hostname.toLowerCase());
  } catch {
    return false;
  }
}

/** True when the URL sets its own TLS mode (sslmode=…), which node-postgres lets win. */
export function hasSslMode(url: string): boolean {
  try {
    return new URL(url).searchParams.has("sslmode");
  } catch {
    return false;
  }
}

/** The node-postgres `ssl` option for a connection URL: verified TLS for Supabase, else none. */
export function sslOptionFor(url: string): { ca: string } | undefined {
  return isSupabaseHost(url) && !hasSslMode(url) ? { ca: SUPABASE_ROOT_CA_2021 } : undefined;
}
